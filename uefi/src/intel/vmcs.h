static inline uint8_t __attribute__((always_inline)) vmclear(EFI_PHYSICAL_ADDRESS vmcs)
{
    uint8_t carry;
    uint8_t zero;
    __asm__("vmclear %2\n"
        "setc %0\n"
        "setz %1\n":"=r"(carry),"=r"(zero):"m"(vmcs):"flags");

    return ((zero | carry) == 0);
}

